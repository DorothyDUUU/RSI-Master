#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

FRAMEWORK_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FRAMEWORK_DIR))
from automation.spec_fixes_data import apply_spec_fixes
from generate_configs import CONFIG_TEMPLATE, spec_revision


RUNNER = '''#!/usr/bin/env python3
from __future__ import annotations
import argparse
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BENCH_DIR.parent.parent / "framework"))
from core.generic_runner import dry_run, run

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--limit", type=int, default=3)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--validate-data", action="store_true")
    args = parser.parse_args()
    if args.dry_run:
        dry_run(__import__("json").loads((BENCH_DIR / "spec.json").read_text()))
        if args.validate_data:
            run(BENCH_DIR, args.config, 1, validate_data=True)
        print(f"[dry-run] {BENCH_DIR.name}: spec OK")
        return
    run(BENCH_DIR, args.config, args.limit)

if __name__ == "__main__":
    main()
'''

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--format-dir", type=Path, required=True)
    parser.add_argument("--replace-generated", action="store_true")
    parser.add_argument("--total", type=int, default=200,
                        help="Total registered benchmarks, including hand-written legacy integrations")
    args = parser.parse_args()
    specs = [apply_spec_fixes(json.loads(line))
             for line in args.registry.read_text().splitlines() if line.strip()]
    legacy_ids = []
    for manifest_path in sorted(args.format_dir.glob("*/config.json")):
        directory = manifest_path.parent
        if directory.name == "benchmark_example" or (directory / ".automated-integration").exists():
            continue
        legacy_ids.append(json.loads(manifest_path.read_text())["benchmark-id"])
    specs = [item for item in specs if item["benchmark-id"] not in legacy_ids]
    specs = specs[:args.total - len(legacy_ids)]
    selected_ids = {item["benchmark-id"] for item in specs}
    if args.replace_generated:
        for marker in args.format_dir.glob("*/.automated-integration"):
            if marker.parent.name not in selected_ids:
                shutil.rmtree(marker.parent)
    generated_ids = set()
    for spec in specs:
        benchmark_id = spec["benchmark-id"]
        generated_ids.add(benchmark_id)
        directory = args.format_dir / benchmark_id
        if directory.exists() and not (directory / ".automated-integration").exists():
            # Preserve the three hand-written legacy integrations.
            continue
        if directory.exists() and args.replace_generated:
            shutil.rmtree(directory)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "config").mkdir(exist_ok=True)
        manifest = {
            "benchmark-id": benchmark_id, "benchmark-name": spec["benchmark-name"],
            "domain": spec["domain"], "adapter": spec["adapter"],
            "eval-method": spec["scorer"], "integration-status": "runnable",
            "source": spec["source"], "split": ["default"],
            "license": spec["license"], "resource-class": spec["resource-class"],
        }
        (directory / "config.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
        (directory / "spec.json").write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n")
        (directory / "config" / "config.yaml").write_text(
            CONFIG_TEMPLATE.format(benchmark_id=spec["benchmark-id"],
                                   revision=spec_revision(spec)))
        (directory / "run_benchmark.py").write_text(RUNNER)
        (directory / ".automated-integration").write_text("generated by framework/automation/generate_integrations.py\n")
        (directory / "BENCHMARK.md").write_text(
            f"# {spec['benchmark-name']}\n\n"
            f"- Adapter: `{spec['adapter']}`\n- Scorer: `{spec['scorer']}`\n"
            f"- Dataset revision: `{spec['dataset']['revision']}`\n"
            f"- License: `{spec['license']['spdx']}` ([evidence]({spec['license']['evidence']}))\n"
            f"- Resource class: `light`\n\n"
            "Run `python framework/run_eval.py " + benchmark_id + " --dry-run` (from the repo root) before any model evaluation.\n"
        )
    manifests = [{"benchmark-id": benchmark_id} for benchmark_id in legacy_ids]
    for spec in specs:
        path = args.format_dir / spec["benchmark-id"] / "config.json"
        if path.exists():
            manifests.append({"benchmark-id": spec["benchmark-id"]})
    if len(manifests) != args.total:
        raise SystemExit(f"registered {len(manifests)} benchmarks; expected {args.total}")
    (args.format_dir / "benchmark.json").write_text(json.dumps(manifests, ensure_ascii=False, indent=2) + "\n")
    print(f"generated/updated {len(manifests)} benchmark integrations")


if __name__ == "__main__":
    main()
