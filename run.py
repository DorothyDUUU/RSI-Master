#!/usr/bin/env python3
from __future__ import annotations

import argparse
from datetime import datetime
import importlib
import json
import logging
import os
from pathlib import Path
import sys
from typing import Any

import yaml


PROJECT_ROOT = Path(__file__).parent.resolve()
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from evomaster.core import get_playground_class


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run a RSI-Master playground")
    parser.add_argument("--agent", required=True, help="Playground name, e.g. rsi_master_posttrain")
    parser.add_argument("--config", help="Config path. Defaults to configs/{agent}/config.yaml")
    parser.add_argument(
        "--benchmark",
        help="DEPRECATED (2026-09): use --set evaluation.eval_all.bench_id=<id> instead",
    )
    parser.add_argument("--gpu", help="Override llama_factory_env.cuda_visible_devices and process CUDA_VISIBLE_DEVICES")
    parser.add_argument(
        "--set",
        dest="config_overrides",
        action="append",
        default=[],
        metavar="KEY=VALUE",
        help="Override a config value using dotted paths, e.g. --set training_budget.max_train_samples=2000",
    )
    parser.add_argument("--task", required=True, help="Task text or a .txt/.md file path")
    parser.add_argument("--run-dir", help="Run directory. Defaults to runs/{agent}_{timestamp}")
    parser.add_argument("--images", nargs="+", help="Optional image paths for multimodal tasks")
    args = parser.parse_args()
    if args.benchmark:
        # 保留 --benchmark 参数而非直接删除, 让旧命令得到定向弃用报错, 而不是
        # argparse 的 "unrecognized arguments" (用户看不到迁移指引)。
        parser.error(
            "--benchmark 已弃用 (2026-09): benchmark 统一走 evaluation.eval_all.bench_id。"
            "请改用: run.py ... --set evaluation.eval_all.bench_id=<benchmark id>"
        )
    return args


def setup_logging() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(name)s - %(levelname)s - %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)


def read_task(task_arg: str) -> str:
    path = Path(task_arg)
    if path.suffix.lower() in {".txt", ".md"} and path.exists() and path.is_file():
        return path.read_text(encoding="utf-8").strip()
    return task_arg


def import_playground(agent_name: str) -> None:
    module_name = f"playground.{agent_name}.core"
    importlib.import_module(module_name)


def _parse_override_value(value: str) -> Any:
    try:
        parsed = yaml.safe_load(value)
    except yaml.YAMLError:
        return value
    return value if parsed is None and value.lower() not in {"null", "none", "~"} else parsed


def _set_dotted_value(data: dict[str, Any], dotted_key: str, value: Any) -> None:
    keys = [part for part in dotted_key.split(".") if part]
    if not keys:
        raise ValueError("empty override key")
    cursor: dict[str, Any] = data
    for key in keys[:-1]:
        child = cursor.get(key)
        if not isinstance(child, dict):
            child = {}
            cursor[key] = child
        cursor = child
    cursor[keys[-1]] = value


def _cli_config_overrides(args: argparse.Namespace) -> list[tuple[str, Any]]:
    overrides: list[tuple[str, Any]] = []
    if args.gpu is not None:
        gpu = str(args.gpu)
        overrides.append(("llama_factory_env.cuda_visible_devices", gpu))
        os.environ["CUDA_VISIBLE_DEVICES"] = gpu
    for item in args.config_overrides:
        if "=" not in item:
            raise ValueError(f"Invalid --set override '{item}', expected KEY=VALUE")
        key, raw_value = item.split("=", 1)
        overrides.append((key.strip(), _parse_override_value(raw_value.strip())))
    return overrides


def _materialize_config_with_overrides(config_path: Path, run_dir: Path, args: argparse.Namespace) -> Path:
    overrides = _cli_config_overrides(args)
    if not overrides:
        return config_path
    if not config_path.exists():
        raise FileNotFoundError(f"Config file not found: {config_path}")

    with config_path.open("r", encoding="utf-8") as handle:
        config_data = yaml.safe_load(handle) or {}
    if not isinstance(config_data, dict):
        raise TypeError(f"Config root must be a mapping: {config_path}")

    for key, value in overrides:
        _set_dotted_value(config_data, key, value)

    run_dir.mkdir(parents=True, exist_ok=True)
    output_path = run_dir / "config.override.yaml"
    output_path.write_text(
        "# Auto-generated by run.py from CLI overrides. Do not edit by hand.\n"
        f"# Base config: {config_path}\n"
        + yaml.safe_dump(config_data, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"Using CLI override config: {output_path}")
    return output_path


def main() -> int:
    args = parse_args()
    setup_logging()
    import_playground(args.agent)

    config_path = Path(args.config) if args.config else PROJECT_ROOT / "configs" / args.agent / "config.yaml"
    if not config_path.is_absolute():
        config_path = (PROJECT_ROOT / config_path).resolve()
    base_config_dir = config_path.parent

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = Path(args.run_dir) if args.run_dir else PROJECT_ROOT / "runs" / f"{args.agent}_{timestamp}"
    if not run_dir.is_absolute():
        run_dir = (PROJECT_ROOT / run_dir).resolve()

    config_path = _materialize_config_with_overrides(config_path, run_dir, args)

    playground = get_playground_class(args.agent, config_dir=base_config_dir, config_path=config_path)
    playground.set_run_dir(run_dir)
    result = playground.run(task_description=read_task(args.task), images=args.images)
    print(json.dumps(result, indent=2, ensure_ascii=False, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
